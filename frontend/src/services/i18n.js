const supportedLocales = Object.keys(translations);
const storedLocale = localStorage.getItem('flix_locale');
const locale = ref(supportedLocales.includes(storedLocale) ? storedLocale : 'bn');

document.documentElement.lang = locale.value;

function t(key) {
  return key.split('.').reduce((value, part) => value?.[part], translations[locale.value]) || key;
}

function setLocale(value) {
  if (!supportedLocales.includes(value)) {
    throw new Error(`Unsupported language: ${value}`);
  }

  locale.value = value;
  document.documentElement.lang = value;
  localStorage.setItem('flix_locale', value);
}

export function useI18n() {
  return { locale, setLocale, t };
}
